'# ──────────────────────────────────────────────────────────────\n'
'#  Simple Event-Based Message Bus\n'
'# ──────────────────────────────────────────────────────────────\n'
'\n'
'class MessageBus:\n'
'    """Publish-subscribe message bus for agent communication."""\n'
'\n'
'    def __init__(self) -> None:\n'
'        self._subscribers: dict[str, list[Callable[[AgentMessage], None]]] = {}\n'
'        self._history: list[AgentMessage] = []\n'
'\n'
'    def subscribe(\n'
'        self, agent_name: str, handler: Callable[[AgentMessage], None]\n'
'    ) -> None:\n'
'        self._subscribers.setdefault(agent_name, []).append(handler)\n'
'\n'
'    def publish(self, message: AgentMessage) -> None:\n'
'        self._history.append(message)\n'
'        handlers = self._subscribers.get(message.receiver, [])\n'
'        for h in handlers:\n'
'            h(message)\n'
'\n'
'    def get_history(\n'
'        self, agent_name: str | None = None\n'
'    ) -> list[AgentMessage]:\n'
'        if agent_name is None:\n'
'            return list(self._history)\n'
'        return [\n'
'            m for m in self._history\n'
'            if m.sender == agent_name or m.receiver == agent_name\n'
'        ]\n'
'\n'
'    @property\n'
'    def total_messages(self) -> int:\n'
'        return len(self._history)\n'
'\n'
'\n'
'# ── Demo ──\n'
'bus = MessageBus()\n'
'received: list[str] = []\n'
'\n'
'\n'
'def supervisor_handler(msg: AgentMessage) -> None:\n'
