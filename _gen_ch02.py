cells.append(md(
'---\n'
'\n'
'## 2.4 Pattern 3 — Handoff Pattern\n'
'\n'
'### Concept\n'
'\n'
'In many analog design flows, failure in one stage does not terminate the\n'
'pipeline — it **redirects** control to an earlier (or alternative) stage\n'
'with rich **error context**.\n'
'\n'
'> **Example:** The Sizing Agent fails to meet a gain target of 60 dB.\n'
'> Rather than crashing, it *hands back* control to the Topology Selection\n'
'> Agent with a structured error report:\n'
'>\n'
'> ```python\n'
'> HandoffContext(\n'
'>     source="SizingAgent",\n'
'>     target="TopologyAgent",\n'
'>     reason="gain_violation",\n'
'>     data={"achieved_gain_db": 52.3, "target_gain_db": 60.0},\n'
'> )\n'
'> ```\n'
'>\n'
'> The Topology Agent can then select a higher-gain topology (e.g.,\n'
'> regulated cascode instead of simple cascode) and re-enter the sizing\n'
'> phase.\n'
'\n'
'### Formal Definition\n'
'\n'
'A **handoff** is a triple $h = (s, t, c)$ where:\n'
'\n'
'- $s \\in \\mathcal{A}$ is the **source** agent\n'
'- $t \\in \\mathcal{A}$ is the **target** agent (may differ from the predecessor)\n'
'- $c$ is a **context object** carrying partial results and error diagnostics\n'
'\n'
'The set of valid handoffs defines a **state machine** over the agent pool.\n'
'\n'
'The **convergence guarantee** relies on monotonic progress:\n'
'\n'
'$$\n'
'\\forall\\, h_i = (s, t, c_i): \\quad \\|c_{i+1}\\|_{\\text{info}} > \\|c_i\\|_{\\text{info}}\n'
'$$\n'
'\n'
'i.e., each handoff must carry strictly more information than the previous one,\n'
'preventing infinite loops over the same failure mode.\n'
))

