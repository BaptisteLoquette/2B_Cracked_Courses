'# ──────────────────────────────────────────────────────────────\n'
'#  Stateful Graph Workflow: DAG with conditional back-edges\n'
'# ──────────────────────────────────────────────────────────────\n'
'\n'
'class GraphNode:\n'
'    """A node in the design-flow graph."""\n'
'\n'
'    def __init__(\n'
'        self,\n'
'        name: str,\n'
'        agent_type: str,\n'
'        func: Callable[[dict], tuple[str, dict]],\n'
'    ) -> None:\n'
'        self.name = name\n'
'        self.agent_type = agent_type\n'
'        self.func = func\n'
'\n'
'    def execute(self, state: dict[str, Any]) -> tuple[str, dict[str, Any]]:\n'
'        return self.func(state)\n'
'\n'
'\n'
'class DesignFlowGraph:\n'
'    """Executable directed graph of agent nodes."""\n'
'\n'
'    def __init__(self) -> None:\n'
'        self.nodes: dict[str, GraphNode] = {}\n'
'        self.edges: dict[str, dict[str, str]] = {}\n'
'\n'
'    def add_node(self, node: GraphNode) -> None:\n'
'        self.nodes[node.name] = node\n'
'\n'
'    def add_edge(\n'
'        self, source: str, target: str, condition: str = "default"\n'
'    ) -> None:\n'
'        self.edges.setdefault(source, {})[condition] = target\n'
'\n'
'    def run(\n'
'        self, entry: str, state: dict[str, Any], max_steps: int = 20\n'
'    ) -> dict[str, Any]:\n'
'        current = entry\n'
'        for step in range(max_steps):\n'
'            node = self.nodes[current]\n'
'            outcome, state = node.execute(state)\n'
'            state.setdefault("trace", []).append((current, outcome))\n'
'            print(f"  Step {step}: {current} -> outcome=\'{outcome}\'")\n'
'\n'
'            transitions = self.edges.get(current, {})\n'
'            next_node = transitions.get(outcome, transitions.get("default"))\n'
'            if next_node is None:\n'
'                print(f"  Terminal node reached: {current}")\n'
'                break\n'
'            current = next_node\n'
'\n'
'        return state\n'
'\n'
'\n'
'# ── Build the analog design DAG ──\n'
'\n'
'def spec_input_fn(s: dict) -> tuple[str, dict]:\n'
