'\n'
'\n'
'def simulation_fn(s: dict) -> tuple[str, dict]:\n'
'    target = s["spec"]["gain_dB"]\n'
'    achieved = round(random.uniform(0.8, 1.1) * target, 1)\n'
'    s["sim_gain_dB"] = achieved\n'
